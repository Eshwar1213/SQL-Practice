--Create the ADMISSION table
CREATE TABLE ADMISSION (
    ADMISSION_ID NUMBER PRIMARY KEY,
    PATIENT_ID NUMBER NOT NULL,
    PHYSICIAN_ID NUMBER NOT NULL,
    ADMIT_DATE DATE,
    DISCHG_DATE DATE,
    ROOM_ID NUMBER,

    CONSTRAINT fk_patient FOREIGN KEY (PATIENT_ID) REFERENCES PATIENT(PATIENT_ID)  ON DELETE CASCADE,
    CONSTRAINT fk_physician FOREIGN KEY (PHYSICIAN_ID) REFERENCES PHYSICIAN(PHYSICIAN_ID) ON DELETE CASCADE,
    CONSTRAINT fk_room FOREIGN KEY (ROOM_ID) REFERENCES ROOM(ROOM_ID)  ON DELETE CASCADE
);


